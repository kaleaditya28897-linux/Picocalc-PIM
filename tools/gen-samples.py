#!/usr/bin/env python3
"""Regenerates src/core/samples_data.c from assets/. Run after editing anything under assets/."""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
out = ["/* Generated by tools/gen-samples.py from assets/; do not edit by hand. */",
       '#include "pim/samples.h"', "", "const pim_sample_t pim_samples[] = {"]
for path in sorted(p for p in (root / "assets").rglob("*") if p.is_file()):
    relative = path.relative_to(root / "assets").as_posix()
    out.append(f'    {{"{relative}",')
    for line in path.read_text().splitlines(keepends=True):
        escaped = line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        out.append(f'     "{escaped}"')
    out[-1] += "},"
out += ["};", "", "const unsigned pim_sample_count = sizeof(pim_samples) / sizeof(pim_samples[0]);", ""]
(root / "src/core/samples_data.c").write_text("\n".join(out))
